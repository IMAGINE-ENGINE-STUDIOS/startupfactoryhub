import { useEffect } from 'react';
import { useLocation } from 'react-router-dom';
import { supabase } from '@/integrations/supabase/client';

const STORAGE_KEY = 'sfh_campaign_clicks_logged';
const VISITOR_KEY = 'sfh_campaign_visitor';

function getVisitorKey(): string {
  try {
    let key = localStorage.getItem(VISITOR_KEY);
    if (!key) {
      key = crypto.randomUUID();
      localStorage.setItem(VISITOR_KEY, key);
    }
    return key;
  } catch {
    return 'unknown';
  }
}

function alreadyLogged(code: string): boolean {
  try {
    const raw = sessionStorage.getItem(STORAGE_KEY);
    const list: string[] = raw ? JSON.parse(raw) : [];
    if (list.includes(code)) return true;
    sessionStorage.setItem(STORAGE_KEY, JSON.stringify([...list, code]));
    return false;
  } catch {
    return false;
  }
}

/**
 * Records a click whenever a visitor lands on a UTM-tagged campaign link
 * generated by the auto-posting engine (utm_content carries the tracking code).
 */
export default function CampaignClickTracking() {
  const location = useLocation();

  useEffect(() => {
    const params = new URLSearchParams(location.search);
    const code = params.get('utm_content');
    const campaign = params.get('utm_campaign');
    if (!code || !campaign) return;
    if (alreadyLogged(code)) return;

    void supabase.from('campaign_link_clicks').insert({
      tracking_code: code,
      campaign,
      source: params.get('utm_source'),
      medium: params.get('utm_medium'),
      landing_path: location.pathname,
      referrer: document.referrer || null,
      visitor_key: getVisitorKey(),
    });
  }, [location.search, location.pathname]);

  return null;
}
